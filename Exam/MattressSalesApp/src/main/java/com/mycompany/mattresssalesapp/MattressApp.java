    private void btnProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcessActionPerformed
        // Read what the user entered
String customer = lblCustomer.getText().trim();
String product = cmbProduct.getSelectedItem().toString();

// Make sure the price is a valid number
double price;
try {
    // Keep only digits, commas and dots (removes hidden characters),
    // and treat a comma as a decimal point
    String priceText = txtPrice.getText().replaceAll("[^0-9.,]", "").replace(',', '.');
    price = Double.parseDouble(priceText);
} catch (NumberFormatException ex) {
    javax.swing.JOptionPane.showMessageDialog(this, "Please enter a valid price.");
    return;
}

// Make sure a name was typed and the price makes sense
if (customer.isEmpty() || price <= 0) {
    javax.swing.JOptionPane.showMessageDialog(this, "Please enter the customer name and a price above 0.");
    return;
}

// Calculations from the paper
double vat = price * 0.15;           // VAT: 15% of the product price
double commission = price * 0.05;    // Commission: 5% of the product price
double total = price + vat + commission;

// Show the results in a message box
String message = "Customer: " + customer + "\n"
        + "Product: " + product + "\n"
        + String.format("VAT amount: %.2f%n", vat)
        + String.format("Commission amount: %.2f%n", commission)
        + String.format("Total sale amount: %.2f", total);
javax.swing.JOptionPane.showMessageDialog(this, message);
// Store the sale details in sales.txt (each sale is added to the end of the file)
try (java.io.PrintWriter writer = new java.io.PrintWriter(new java.io.FileWriter("sales.txt", true))) {
    writer.println("Customer: " + customer);
    writer.println("Product: " + product);
    writer.println(String.format("VAT amount: %.2f", vat));
    writer.println(String.format("Commission amount: %.2f", commission));
    writer.println(String.format("Total sale amount: %.2f", total));
    writer.println("------------------------------");
} catch (java.io.IOException ex) {
    javax.swing.JOptionPane.showMessageDialog(this, "Could not save the sale: " + ex.getMessage());
}
    }//GEN-LAST:event_btnProcessActionPerformed

